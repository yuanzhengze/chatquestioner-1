function categoryOf(id) {
  if (EXCLUDE[id]) return "excluded";
  if (VISUAL.has(id)) return "visual";
  if (GENRE.has(id)) return "genre";
  if (MOOD.has(id)) return "mood";
  if (FEATURE.has(id)) return "feature";
  if (THEME.has(id)) return "theme";
  return "gameplay";
}

function aliasesFor(id, label) {
  const extra = EXTRA[id] || [];
  const override = OVERRIDE[id];
  const base = override || (label.length >= 2 ? [label] : []);
  const all = [...base, ...extra].map((item) => item.trim()).filter((item) => item.length >= 2);
  return [...new Set(all)];
}

