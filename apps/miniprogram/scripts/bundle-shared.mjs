import * as esbuild from "esbuild";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

await esbuild.build({
  absWorkingDir: root,
  entryPoints: [resolve(here, "shared-entry.ts")],
  outfile: resolve(root, "lib/shared.js"),
  bundle: true,
  format: "iife",
  globalName: "cqShared",
  platform: "neutral",
  target: ["es2018"],
  logLevel: "info",
  banner: {
    js: "/* AUTO-GENERATED by scripts/bundle-shared.mjs — do not edit */\n",
  },
  footer: {
    js: "module.exports = cqShared;\n",
  },
});

console.log("[miniprogram] bundled lib/shared.js");
